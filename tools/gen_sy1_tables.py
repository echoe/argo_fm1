"""The Synth1 (.sy1) tables of the editor's importer (web/editor.html, SY1), from fm1-sy1's measured tables.

  python3 tools/gen_sy1_tables.py PATH/TO/fm1-sy1/app/dsp/s1_tables.c          # the JS block on stdout
  python3 tools/gen_sy1_tables.py PATH/TO/s1_tables.c --write web/editor.html  # replace the block between the markers
  python3 tools/gen_sy1_tables.py PATH/TO/s1_tables.c --check web/editor.html  # exit 1 if the block there differs

The tables are fm1-sy1's (https://github.com/fenderberg/fm1-sy1, MIT), themselves oxo_synth2's measurements of the original
(chab/oxo_synth2, MIT): see CREDITS.md. Only what the importer reads is taken: the envelope times, the sustain, the filter's
ladder cutoffs and key tracking, OSC 2's pitch and fine tables, the LFO and unison and portamento tables, the 99 parameters'
ranges and defaults, and the rules that convert a patch of an older Synth1 version.
"""
import re
import sys

BEGIN = "/*SY1-TABLES-BEGIN*/"
END = "/*SY1-TABLES-END*/"
FLOAT_TABLES = ["attack_s", "env_tau_s", "amp_sustain", "ladder_hz", "kbd_track", "lfo_cents", "unison_cents", "porta_tau"]
INT_TABLES = ["osc2_semis", "fine_cents"]


def num(x):
    s = ("%.6g" % x)
    return s


def block(src):
    def body(name):
        m = re.search(r"%s\s*(?:\[[^\]]*\])+\s*=\s*\{(.*?)\n\};" % re.escape(name), src, re.S)
        if not m:
            sys.exit("gen_sy1_tables: %s not found in the C file" % name)
        return m.group(1)

    def nums(name):
        return [float(x) for x in re.findall(r"-?\d+\.?\d*(?:e-?\d+)?", body(name).replace("f", ""))]

    out = [BEGIN, "  /* generated by tools/gen_sy1_tables.py from fm1-sy1's s1_tables.c (MIT; oxo_synth2's measurements): do not edit */",
           "  const T = {"]
    for n in FLOAT_TABLES:
        a = nums("s1_t_" + n)
        assert len(a) == 128, n
        out.append("    %s: [%s]," % (n, ",".join(num(x) for x in a)))
    for n in INT_TABLES:
        a = nums("s1_t_" + n)
        assert len(a) == 128, n
        out.append("    %s: [%s]," % (n, ",".join(str(int(x)) for x in a)))
    for n in ("min", "max", "def"):
        a = [int(x) for x in re.findall(r"-?\d+", body("s1_param_" + n))]
        assert len(a) == 99, n
        out.append("    p%s: [%s]," % (n, ",".join(map(str, a))))
    tab = [int(x) for x in re.findall(r"\d+", body("s1_legacy_tab").replace("{", " ").replace("}", " "))]
    assert len(tab) == 13 * 128
    out.append("    legacyTab: [%s]," % ",".join(map(str, tab)))
    rules = re.findall(r"\{\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(\d+)\s*\}", body("s1_legacy_rules"))
    assert len(rules) == 47
    out.append("    legacyRules: [%s]," % ",".join("[%s,%s,%s,%s]" % r for r in rules))
    out.append("  };")
    out.append("  " + END)
    return "\n".join(out)


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    src = open(sys.argv[1]).read()
    b = block(src)
    if len(sys.argv) == 2:
        print(b)
        return
    mode, path = sys.argv[2], sys.argv[3]
    html = open(path).read()
    i, j = html.find(BEGIN), html.find(END)
    if i < 0 or j < 0:
        sys.exit("gen_sy1_tables: no %s .. %s markers in %s" % (BEGIN, END, path))
    cur = html[i:j + len(END)]
    # the marker line is indented in the file: compare without the indent of the first line
    if mode == "--check":
        if cur.strip() != b.strip():
            print("gen_sy1_tables: the SY1 tables in %s are not the generator's output" % path)
            sys.exit(1)
        print("gen_sy1_tables: tables up to date")
    elif mode == "--write":
        open(path, "w").write(html[:i] + b + html[j + len(END):])
    else:
        sys.exit(__doc__)


main()
